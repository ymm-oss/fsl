// Spike (#1908): generate the TypeScript entry point for a proved core.
//
// The compiled Dafny module (<Name>.cjs) works on Dafny values. This emits
// <Name>.ts, a reducer-style API over plain JSON:
//
//   init(sizes): State
//   step(sizes, state, action): State | null      null = the spec does not allow it
//   validate(sizes, state): void                  throws unless the state is one the proof covers
//
// State and Action have the shape of `fslc replay` trace events
// ({ action, params } and the observed state), so a log of them replays as is.
// Every value that crosses the boundary is checked here: sizes and parameters
// must be safe integers, and an incoming state must satisfy Wf and Inv, the
// precondition of the proved <action>_StepPreserves. A state from init/step
// always does; one read from storage is checked again on every call.
//
// usage: node gen-ts.mjs <kernel.json> [--widen T1,T2] > <Name>.ts

import { readFileSync } from "node:fs";
import { widenedTypes } from "./gen.mjs";

export function generateTs(kernel, widen = []) {
  const name = kernel.spec.name;
  const widened = widenedTypes(kernel, widen);
  const types = Object.fromEntries(
    kernel.types.map((t) => [t.name, { lo: t.definition.lo, hi: t.definition.hi, widened: widened.includes(t.name) }]),
  );
  const tsType = (ty) => {
    switch (ty.kind) {
      case "named":
      case "int":
        return "number";
      case "bool":
        return "boolean";
      case "option":
        return ty.item.kind === "option"
          ? `{ readonly kind: "none" } | { readonly kind: "some"; readonly value: ${tsType(ty.item)} }`
          : `${tsType(ty.item)} | null`;
      case "map":
        return `Readonly<Record<string, ${tsType(ty.value)}>>`;
      default:
        throw new Error(`type kind ${ty.kind}`);
    }
  };
  const schema = {
    widened,
    types,
    state: kernel.state.map((s) => ({ name: s.name, type: s.type })),
    actions: kernel.actions.map((a) => ({ name: a.name, params: a.parameters.map((p) => ({ name: p.name, type: p.type.name })) })),
  };
  const sizes = widened.length ? `{ ${widened.map((t) => `readonly ${t}: number`).join("; ")} }` : "Record<string, never>";
  const state = `{\n${kernel.state.map((s) => `  readonly ${s.name}: ${tsType(s.type)};`).join("\n")}\n}`;
  const action = kernel.actions
    .map((a) => `  | { readonly action: "${a.name}"; readonly params: { ${a.parameters.map((p) => `readonly ${p.name}: number`).join("; ")} } }`)
    .join("\n");

  return `// GENERATED by rust/spikes/dafny-core/gen-ts.mjs from ${kernel.spec.source.file}. Do not edit.
// SPDX-License-Identifier: Apache-2.0
//
// ${name}: the Dafny-proved core (./${name}.cjs) as a reducer over plain JSON.
// Proved for every size of: ${widened.join(", ") || "(no widened types)"}.

import core from "./${name}.cjs";

/** Sizes of the types proved for every size; ids of type T are 0..T-1. */
export type Sizes = ${sizes};
/** The state, in the shape fslc replay observes. */
export type State = ${state};
/** One action instance, in the shape of an fslc replay trace event. */
export type Action =
${action};

/** A value that is not an input the proved core accepts. */
export class CoreInputError extends Error {}

const SCHEMA: any = ${JSON.stringify(schema)};

// Looked up on every call (not captured), so the differential check's
// negative controls can replace a compiled function in place.
const D = (): any => core.M.__default;
const fn = (dafnyName: string): any => D()[dafnyName.replace(/_/g, "__")];
const big = (n: number): any => new core.BigNumber(n);

function int(v: unknown, what: string): number {
  if (typeof v !== "number" || !Number.isSafeInteger(v)) throw new CoreInputError(\`\${what}: expected a safe integer, got \${String(v)}\`);
  return v;
}

function keys(sizes: Sizes, typeName: string): string[] {
  const t = SCHEMA.types[typeName];
  const n = t.widened ? (sizes as any)[typeName] : t.hi - t.lo + 1;
  return Array.from({ length: n }, (_, k) => String((t.widened ? 0 : t.lo) + k));
}

function config(sizes: Sizes): any {
  if (typeof sizes !== "object" || sizes === null) throw new CoreInputError("sizes: expected an object");
  const extra = Object.keys(sizes).filter((k) => !SCHEMA.widened.includes(k));
  if (extra.length) throw new CoreInputError(\`sizes: unknown type \${extra.join(", ")}\`);
  const args = SCHEMA.widened.map((t: string) => {
    const n = int((sizes as any)[t], \`sizes.\${t}\`);
    if (n < 0) throw new CoreInputError(\`sizes.\${t}: negative\`);
    return big(n);
  });
  return core.M.Config.create_Config(...args);
}

function decode(sizes: Sizes, ty: any, v: any, path: string): any {
  switch (ty.kind) {
    case "named":
    case "int":
      return big(int(v, path));
    case "bool":
      if (typeof v !== "boolean") throw new CoreInputError(\`\${path}: expected a boolean\`);
      return v;
    case "option": {
      const nested = ty.item.kind === "option";
      if (nested ? v?.kind === "none" : v === null) return core.M.Option.create_None();
      if (nested && v?.kind !== "some") throw new CoreInputError(\`\${path}: expected { kind: "none" | "some" }\`);
      return core.M.Option.create_Some(decode(sizes, ty.item, nested ? v.value : v, path));
    }
    case "map": {
      if (typeof v !== "object" || v === null || Array.isArray(v)) throw new CoreInputError(\`\${path}: expected an object\`);
      const ks = keys(sizes, ty.key.name);
      const have = Object.keys(v);
      if (have.length !== ks.length || ks.some((k) => !Object.hasOwn(v, k)))
        throw new CoreInputError(\`\${path}: keys must be exactly \${ks[0] ?? "(none)"}..\${ks[ks.length - 1] ?? ""}\`);
      return core._dafny.Seq.of(...ks.map((k) => decode(sizes, ty.value, v[k], \`\${path}[\${k}]\`)));
    }
  }
  throw new Error(\`type kind \${ty.kind}\`);
}

function encode(sizes: Sizes, ty: any, d: any, path: string): any {
  switch (ty.kind) {
    case "named":
    case "int": {
      const n = d.toNumber();
      if (!Number.isSafeInteger(n)) throw new RangeError(\`\${path}: \${d.toString()} is not a safe integer\`);
      return n;
    }
    case "bool":
      return d;
    case "option": {
      const nested = ty.item.kind === "option";
      if (d.is_None) return nested ? { kind: "none" } : null;
      const x = encode(sizes, ty.item, d.dtor_value, path);
      return nested ? { kind: "some", value: x } : x;
    }
    case "map": {
      const ks = keys(sizes, ty.key.name);
      return Object.fromEntries(Array.from(d as Iterable<any>, (x, k) => [ks[k], encode(sizes, ty.value, x, \`\${path}[\${ks[k]}]\`)]));
    }
  }
  throw new Error(\`type kind \${ty.kind}\`);
}

function toCore(c: any, sizes: Sizes, state: State): any {
  if (typeof state !== "object" || state === null) throw new CoreInputError("state: expected an object");
  const extra = Object.keys(state).filter((k) => !SCHEMA.state.some((s: any) => s.name === k));
  if (extra.length) throw new CoreInputError(\`state: unknown field \${extra.join(", ")}\`);
  const st = fn("Mk")(...SCHEMA.state.map((s: any) => decode(sizes, s.type, (state as any)[s.name], \`state.\${s.name}\`)));
  // StepPreserves is proved from Inv (which includes Wf); outside it the core's behaviour is unproved.
  if (!fn("Inv")(c, st)) throw new CoreInputError("state: outside the type bounds or breaks an invariant");
  return st;
}

function fromCore(sizes: Sizes, st: any): State {
  return Object.fromEntries(SCHEMA.state.map((s: any) => [s.name, encode(sizes, s.type, fn(\`Get_\${s.name}\`)(st), \`state.\${s.name}\`)])) as State;
}

/** The initial state for these sizes. */
export function init(sizes: Sizes): State {
  return fromCore(sizes, fn("Init")(config(sizes)));
}

/** Throws CoreInputError unless the state is one the proof covers (type bounds and invariants hold). */
export function validate(sizes: Sizes, state: State): void {
  toCore(config(sizes), sizes, state);
}

/** The next state, or null when the spec does not allow the action here (a guard fails or an id is out of range). */
export function step(sizes: Sizes, state: State, action: Action): State | null {
  const c = config(sizes);
  const st = toCore(c, sizes, state);
  const a = SCHEMA.actions.find((x: any) => x.name === (action as any)?.action);
  if (!a) throw new CoreInputError(\`action: unknown \${String((action as any)?.action)}\`);
  const params = (action as any).params;
  if (typeof params !== "object" || params === null) throw new CoreInputError("action.params: expected an object");
  const names = a.params.map((p: any) => p.name);
  const extra = Object.keys(params).filter((k) => !names.includes(k));
  if (extra.length) throw new CoreInputError(\`action.params: unknown \${extra.join(", ")}\`);
  const args = names.map((p: string) => big(int(params[p], \`action.params.\${p}\`)));
  const r = fn(\`\${a.name}_Step\`)(c, st, ...args);
  return r.is_Some ? fromCore(sizes, r.dtor_value) : null;
}
`;
}

// Declarations for the compiled module, so `import core from "./<Name>.cjs"` type-checks.
export const CJS_DTS = `// GENERATED by rust/spikes/dafny-core/gen-ts.mjs. Do not edit.
declare const core: { M: any; _dafny: any; BigNumber: any };
export = core;
`;

if (import.meta.url === `file://${process.argv[1]}`) {
  const args = process.argv.slice(2);
  const file = args.find((a) => !a.startsWith("--"));
  const wi = args.indexOf("--widen");
  const widen = wi >= 0 ? args[wi + 1].split(",").filter(Boolean) : [];
  process.stdout.write(generateTs(JSON.parse(readFileSync(file, "utf8")), widen));
}
